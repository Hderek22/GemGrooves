#!/usr/bin/env node
// Regenerates apps/web/src/config/contracts.generated.ts from compiled
// artifacts and deployment records. Run after "compile" and/or "deploy".
const fs = require("fs");
const path = require("path");

const CONTRACTS_ROOT = path.join(__dirname, "..");
const ARTIFACTS_DIR = path.join(CONTRACTS_ROOT, "artifacts", "contracts");
const DEPLOYMENTS_DIR = path.join(CONTRACTS_ROOT, "deployments");
const OUT_DIR = path.join(CONTRACTS_ROOT, "..", "..", "apps", "web", "src", "config");
const OUT_FILE = path.join(OUT_DIR, "contracts.generated.ts");

// Minimal read/write surface for third-party ERC-20s (USDC/DAI) — not
// generated from an artifact since we never deploy the real tokens ourselves.
const ERC20_MINIMAL_ABI = [
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ type: "uint8" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "account", type: "address" }], outputs: [{ type: "uint256" }] },
  {
    type: "function",
    name: "allowance",
    stateMutability: "view",
    inputs: [
      { name: "owner", type: "address" },
      { name: "spender", type: "address" },
    ],
    outputs: [{ type: "uint256" }],
  },
  {
    type: "function",
    name: "approve",
    stateMutability: "nonpayable",
    inputs: [
      { name: "spender", type: "address" },
      { name: "amount", type: "uint256" },
    ],
    outputs: [{ type: "bool" }],
  },
];

function loadAbi(contractFile, contractName) {
  const artifactPath = path.join(ARTIFACTS_DIR, contractFile, `${contractName}.json`);
  if (!fs.existsSync(artifactPath)) {
    throw new Error(
      `Missing artifact: ${artifactPath}\nRun "npm run compile -w packages/contracts" first.`
    );
  }
  const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
  return artifact.abi;
}

function loadDeployments() {
  if (!fs.existsSync(DEPLOYMENTS_DIR)) return {};
  const files = fs.readdirSync(DEPLOYMENTS_DIR).filter((f) => f.endsWith(".json"));
  const byChainId = {};
  for (const file of files) {
    const record = JSON.parse(fs.readFileSync(path.join(DEPLOYMENTS_DIR, file), "utf8"));
    byChainId[record.chainId] = {
      network: record.network,
      nft: record.contracts.GemGroovesNFT,
      marketplace: record.contracts.GemGroovesMarketplace,
    };
  }
  return byChainId;
}

function main() {
  const nftAbi = loadAbi("GemGroovesNFT.sol", "GemGroovesNFT");
  const marketplaceAbi = loadAbi("GemGroovesMarketplace.sol", "GemGroovesMarketplace");
  const trackSplitterAbi = loadAbi("TrackSplitter.sol", "TrackSplitter");
  const deployments = loadDeployments();

  fs.mkdirSync(OUT_DIR, { recursive: true });

  const contents = `// AUTO-GENERATED by packages/contracts/scripts/sync-web-config.js
// Do not edit by hand — run "npm run sync:web -w packages/contracts" after
// compiling/deploying to regenerate.

export const gemGroovesNftAbi = ${JSON.stringify(nftAbi, null, 2)} as const;

export const gemGroovesMarketplaceAbi = ${JSON.stringify(marketplaceAbi, null, 2)} as const;

export const trackSplitterAbi = ${JSON.stringify(trackSplitterAbi, null, 2)} as const;

export const erc20MinimalAbi = ${JSON.stringify(ERC20_MINIMAL_ABI, null, 2)} as const;

export type GemGroovesDeployment = {
  network: string;
  nft: \`0x\${string}\`;
  marketplace: \`0x\${string}\`;
};

export const deployments: Record<number, GemGroovesDeployment> = ${JSON.stringify(
    deployments,
    null,
    2
  )};
`;

  fs.writeFileSync(OUT_FILE, contents);
  console.log(`Wrote ${OUT_FILE}`);
  console.log(
    `Chains configured: ${Object.keys(deployments).join(", ") || "(none yet — deploy first)"}`
  );
}

main();
